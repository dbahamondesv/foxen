let activeLocale: Locale = DEFAULT_LOCALE;

/** Valida un idioma desconocido (archivo o localStorage). */
export function normalizeLocale(value: unknown): Locale | null {
  return value === 'es' || value === 'en' ? value : null;
}

/** Interpola marcadores `{nombre}`; si falta una variable se deja visible. */
export function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in vars ? String(vars[key]) : match,
  );
}

/** Traduce una cadena. En espanol devuelve el texto original. */
export function translate(text: string, vars?: Vars, locale: Locale = activeLocale): string {
  const template = locale === 'en' ? (EN[text] ?? text) : text;
  return interpolate(template, vars);
}

export function getLocale(): Locale {
  return activeLocale;
}

export function setActiveLocale(locale: Locale): void {
  activeLocale = locale;
}

/** Aplica el idioma al documento (lectores de pantalla y corrector). */
export function applyLocale(locale: Locale): void {
  activeLocale = locale;
  if (typeof document !== 'undefined') {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
  }
}

function readCache(): Locale | null {
  try {
    return normalizeLocale(window.localStorage.getItem(LOCALE_STORAGE_KEY));
  } catch {
    return null;
  }
}

function writeCache(locale: Locale): void {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Sin cache se aplica tras la respuesta del backend; no es fatal.
  }
}

/** Idioma para el primer pintado (cache); el backend confirma despues. */
export function loadLocale(): Locale {
  return readCache() ?? DEFAULT_LOCALE;
}

/**
 * Lee el idioma persistido en Rust y migra la cache de versiones anteriores.
 * Devuelve `null` si el usuario nunca eligio idioma.
 */
export async function loadStoredLocale(): Promise<Locale | null> {
  const legacy = readCache();
  try {
    const settings = await ipc.settingsLoad();
    const stored = normalizeLocale(settings.locale);
    if (!stored && legacy) {
      void ipc.settingsSaveLocale(legacy).catch(() => undefined);
      return legacy;
    }
    return stored;
  } catch {
    return legacy;
  }
}

/** Persiste el idioma en Rust y actualiza la cache de arranque. */
export function saveLocale(locale: Locale): void {
  writeCache(locale);
  void ipc.settingsSaveLocale(locale).catch(() => undefined);
}
